def clean_whisper_loops(text: str) -> str:
    """
    Deduplicate repeated loop hallucinations generated by Whisper during silences,
    handling both unpunctuated loops (e.g. 'the nature of the nature of') and punctuated phrases.
    """
    if not text or not text.strip():
        return ""
    curr = text.strip()

    # 1. Multi-gram phrase deduplication: collapse 1 to 8 words repeated >= 2 times
    pattern = r"(\b(?:[a-zA-Z\']+\s*){1,8}\b)(?:\s+\1){1,}"
    prev = None
    for _ in range(5):
        curr = re.sub(pattern, r"\1", curr, flags=re.IGNORECASE)
        if curr == prev:
            break
        prev = curr

    # 2. Deduplicate consecutive punctuated clauses / phrases
    phrases = re.split(r"[,.!?]\s*", curr)
    cleaned_phrases = []
    for p in phrases:
        p_clean = p.strip()
        if not p_clean:
            continue
        if len(cleaned_phrases) >= 1 and p_clean.lower() == cleaned_phrases[-1].lower():
            continue
        if len(cleaned_phrases) >= 2 and p_clean.lower() == cleaned_phrases[-2].lower():
            continue
        cleaned_phrases.append(p_clean)

    return ", ".join(cleaned_phrases)


def extract_acoustic_features(audio_path: str) -> Dict[str, float]:
    feats = {}
    try:
        y, sr = sf.read(audio_path)
        if len(y.shape) > 1:
            y = np.mean(y, axis=1)
        if sr != AUDIO_SAMPLE_RATE:
            y = librosa.resample(y, orig_sr=sr, target_sr=AUDIO_SAMPLE_RATE)
            sr = AUDIO_SAMPLE_RATE

        total_samples = len(y)
        duration = total_samples / float(sr)
        feats["audio_duration"] = duration

        # 1. Zero-Crossing Rate
        zcr = librosa.feature.zero_crossing_rate(y, frame_length=2048, hop_length=512)[0]
        feats["zcr_mean"] = float(np.mean(zcr))
        feats["zcr_std"] = float(np.std(zcr))
        feats["zcr_max"] = float(np.max(zcr))

        # 2. RMS Energy Dynamics
        rms = librosa.feature.rms(y=y, frame_length=2048, hop_length=512)[0]
        feats["rms_mean"] = float(np.mean(rms))
        feats["rms_std"] = float(np.std(rms))
        feats["rms_max"] = float(np.max(rms))
        feats["rms_dyn_range"] = float(np.max(rms) - np.min(rms)) if len(rms) > 0 else 0.0

        # 3. Spectral Centroid & Rolloff & Flatness
        cent = librosa.feature.spectral_centroid(y=y, sr=sr, hop_length=512)[0]
        feats["spec_cent_mean"] = float(np.mean(cent))
        feats["spec_cent_std"] = float(np.std(cent))

        rolloff = librosa.feature.spectral_rolloff(y=y, sr=sr, hop_length=512, roll_percent=0.85)[0]
        feats["spec_rolloff_mean"] = float(np.mean(rolloff))
        feats["spec_rolloff_std"] = float(np.std(rolloff))

        flatness = librosa.feature.spectral_flatness(y=y, hop_length=512)[0]
        feats["spec_flatness_mean"] = float(np.mean(flatness))
        feats["spec_flatness_std"] = float(np.std(flatness))

        # 4. MFCCs (13 coefficients) + Delta MFCCs (speech transitions)
        mfccs = librosa.feature.mfcc(y=y, sr=sr, n_mfcc=13, hop_length=512)
        mfcc_delta = librosa.feature.delta(mfccs)
        for i in range(13):
            feats[f"mfcc_{i+1}_mean"] = float(np.mean(mfccs[i]))
            feats[f"mfcc_{i+1}_std"] = float(np.std(mfccs[i]))
            feats[f"mfcc_delta_{i+1}_mean"] = float(np.mean(mfcc_delta[i]))
            feats[f"mfcc_delta_{i+1}_std"] = float(np.std(mfcc_delta[i]))

        # 5. Spectral Contrast (6 subbands)
        contrast = librosa.feature.spectral_contrast(y=y, sr=sr, hop_length=512)
        for b in range(min(6, contrast.shape[0])):
            feats[f"spec_contrast_{b+1}_mean"] = float(np.mean(contrast[b]))
            feats[f"spec_contrast_{b+1}_std"] = float(np.std(contrast[b]))

        # 6. Chroma STFT (Harmonic speech stability)
        chroma = librosa.feature.chroma_stft(y=y, sr=sr, hop_length=512)
        feats["chroma_mean"] = float(np.mean(chroma))
        feats["chroma_std"] = float(np.std(chroma))

        # 7. High-frequency noise ratio
        fft_vals = np.abs(np.fft.rfft(y[: min(len(y), 16000 * 5)]))
        freqs = np.fft.rfftfreq(len(y[: min(len(y), 16000 * 5)]), 1.0 / sr)
        high_freq_energy = np.sum(fft_vals[freqs >= 4000] ** 2)
        total_energy = np.sum(fft_vals**2) + 1e-9
        feats["high_freq_ratio"] = float(high_freq_energy / total_energy)

        # 8. Pitch (F0) Dynamics via fast YIN
        f0 = librosa.yin(y, fmin=50, fmax=400, sr=sr, hop_length=2048)
        valid_f0 = f0[(f0 > 55) & (f0 < 390)]
        if len(valid_f0) > 10:
            feats["pitch_f0_mean"] = float(np.mean(valid_f0))
            feats["pitch_f0_std"] = float(np.std(valid_f0))
            feats["pitch_f0_range"] = float(np.percentile(valid_f0, 95) - np.percentile(valid_f0, 5))
            feats["pitch_voiced_ratio"] = float(len(valid_f0) / max(1, len(f0)))
        else:
            feats["pitch_f0_mean"] = 0.0
            feats["pitch_f0_std"] = 0.0
            feats["pitch_f0_range"] = 0.0
            feats["pitch_voiced_ratio"] = 0.0

    except Exception as e:
        logger.error(f"Error computing acoustic features for {audio_path}: {e}")
        feats = {
            "audio_duration": 0.0,
            "zcr_mean": 0.0,
            "zcr_std": 0.0,
            "zcr_max": 0.0,
            "rms_mean": 0.0,
            "rms_std": 0.0,
            "rms_max": 0.0,
            "rms_dyn_range": 0.0,
            "spec_cent_mean": 0.0,
            "spec_cent_std": 0.0,
            "spec_rolloff_mean": 0.0,
            "spec_rolloff_std": 0.0,
            "spec_flatness_mean": 0.0,
            "spec_flatness_std": 0.0,
            "high_freq_ratio": 0.0,
            "chroma_mean": 0.0,
            "chroma_std": 0.0,
            "pitch_f0_mean": 0.0,
            "pitch_f0_std": 0.0,
            "pitch_f0_range": 0.0,
            "pitch_voiced_ratio": 0.0,
        }
        for i in range(13):
            feats[f"mfcc_{i+1}_mean"] = 0.0
            feats[f"mfcc_{i+1}_std"] = 0.0
            feats[f"mfcc_delta_{i+1}_mean"] = 0.0
            feats[f"mfcc_delta_{i+1}_std"] = 0.0
        for b in range(6):
            feats[f"spec_contrast_{b+1}_mean"] = 0.0
            feats[f"spec_contrast_{b+1}_std"] = 0.0
    return feats


# Syntactic Lexicons & Patterns
SUBORDINATING = {
    "because", "although", "since", "while", "whereas", "if", "unless",
    "which", "whose", "whom", "whether", "though", "even", "after", "before", "as"
}
COORDINATING = {"and", "but", "or", "nor", "so", "yet", "for"}
PREPOSITIONS = {
    "in", "on", "at", "by", "for", "with", "about", "against", "between",
    "into", "through", "during", "before", "after", "above", "below", "to", "from",
    "up", "down", "over", "under", "within", "without"
}
MODAL_VERBS = {"can", "could", "may", "might", "shall", "should", "will", "would", "must"}
FILLERS = {"uh", "um", "ah", "er", "like", "you know", "i mean"}
CONDITIONALS = {"if", "unless", "whether", "provided", "suppose", "assuming"}
RELATIVES = {"who", "whom", "whose", "which", "that"}

# Grammar Error Regex Patterns
ART_ERRORS = [r"\ba [aeiou]\w+", r"\ban [bcdfghjklmnpqrstvwxyz]\w+"]
SV_DISAGREEMENT = [
    r"\b(he|she|it) have\b",
    r"\b(they|we|you) was\b",
    r"\b(he|she|it) do\b",
    r"\b(birds|trees|leaves|people|children|kids|students|boys|girls) (plays|dances|goes|likes|eats|runs|walks|wants|says|comes|makes)\b",
    r"\b(he|she|it) (play|dance|go|like|eat|run|walk|want|say|come|make)\b",
]
PASSIVE_VOICE = [r"\b(is|are|was|were|been|being) \w+ed\b", r"\b(is|are|was|were|been|being) (seen|done|made|given|taken|written)\b"]


def extract_linguistic_features(raw_text: str) -> Dict[str, float]:
    feats = {}
    cleaned = clean_whisper_loops(raw_text)
    words = re.findall(r"\b[a-zA-Z']+\b", cleaned.lower())
    num_words = len(words)

    feats["text_char_count"] = float(len(cleaned))
    feats["text_word_count"] = float(num_words)

    if num_words == 0:
        feats["avg_word_len"] = 0.0
        feats["lexical_ttr"] = 0.0
        feats["root_ttr"] = 0.0
        feats["log_ttr"] = 0.0
        feats["maas_index"] = 0.0
        feats["sentence_count"] = 0.0
        feats["avg_sentence_len"] = 0.0
        feats["sentence_len_std"] = 0.0
        feats["sentence_len_max"] = 0.0
        feats["sentence_len_median"] = 0.0
        feats["run_on_density"] = 0.0
        feats["fragment_density"] = 0.0
        feats["comma_density"] = 0.0
        feats["subordinate_ratio"] = 0.0
        feats["coordination_ratio"] = 0.0
        feats["preposition_density"] = 0.0
        feats["modal_ratio"] = 0.0
        feats["adverb_ly_density"] = 0.0
        feats["academic_words_density"] = 0.0
        feats["disfluency_filler_count"] = 0.0
        feats["disfluency_filler_density"] = 0.0
        feats["repetition_count"] = 0.0
        feats["repetition_density"] = 0.0
        feats["unique_bigrams_ratio"] = 0.0
        feats["article_error_density"] = 0.0
        feats["sv_disagreement_density"] = 0.0
        feats["passive_voice_density"] = 0.0
        feats["conditional_density"] = 0.0
        feats["relative_pronoun_density"] = 0.0
        return feats

    feats["avg_word_len"] = float(np.mean([len(w) for w in words]))

    # 1. Lexical Diversity metrics
    unique_words = set(words)
    V = len(unique_words)
    N = num_words
    feats["lexical_ttr"] = float(V / N)
    feats["root_ttr"] = float(V / np.sqrt(N))
    feats["log_ttr"] = float(np.log(max(1, V)) / np.log(max(2, N)))
    feats["maas_index"] = float((np.log(max(2, N)) - np.log(max(1, V))) / (np.log(max(2, N)) ** 2))

    if N > 1:
        bigrams = [f"{words[i]}_{words[i+1]}" for i in range(N - 1)]
        feats["unique_bigrams_ratio"] = float(len(set(bigrams)) / len(bigrams))
    else:
        feats["unique_bigrams_ratio"] = 0.0

    # 2. Sentence Dynamics & Clause boundaries
    sentences = [s.strip() for s in re.split(r"[.!?]+", cleaned) if s.strip()]
    num_sentences = max(1, len(sentences))
    feats["sentence_count"] = float(num_sentences)
    feats["avg_sentence_len"] = float(N / num_sentences)

    sent_lens = [len(re.findall(r"\b\w+\b", s)) for s in sentences]
    feats["sentence_len_std"] = float(np.std(sent_lens)) if len(sent_lens) > 1 else 0.0
    feats["sentence_len_max"] = float(np.max(sent_lens)) if sent_lens else 0.0
    feats["sentence_len_median"] = float(np.median(sent_lens)) if sent_lens else 0.0

    # Run-on sentences (> 25 words) and fragmented sentences (< 4 words)
    run_on_count = sum(1 for sl in sent_lens if sl > 25)
    fragment_count = sum(1 for sl in sent_lens if sl < 4)
    feats["run_on_density"] = float(run_on_count / num_sentences)
    feats["fragment_density"] = float(fragment_count / num_sentences)

    # Comma density (prosodic/clause boundary indicator)
    comma_count = cleaned.count(",")
    feats["comma_density"] = float(comma_count / N)

    # 3. Syntactic structures & complexity
    sub_count = sum(1 for w in words if w in SUBORDINATING)
    coord_count = sum(1 for w in words if w in COORDINATING)
    prep_count = sum(1 for w in words if w in PREPOSITIONS)
    modals = sum(1 for w in words if w in MODAL_VERBS)
    adverbs_ly = sum(1 for w in words if w.endswith("ly") and len(w) > 4)
    academic = sum(1 for w in words if len(w) >= 8)
    conds = sum(1 for w in words if w in CONDITIONALS)
    rels = sum(1 for w in words if w in RELATIVES)

    feats["subordinate_ratio"] = float(sub_count / N)
    feats["coordination_ratio"] = float(coord_count / N)
    feats["preposition_density"] = float(prep_count / N)
    feats["modal_ratio"] = float(modals / N)
    feats["adverb_ly_density"] = float(adverbs_ly / N)
    feats["academic_words_density"] = float(academic / N)
    feats["conditional_density"] = float(conds / N)
    feats["relative_pronoun_density"] = float(rels / N)

    # 4. Grammar error and passive voice patterns
    lower_clean = cleaned.lower()
    art_errors = sum(len(re.findall(pat, lower_clean)) for pat in ART_ERRORS)
    sv_errors = sum(len(re.findall(pat, lower_clean)) for pat in SV_DISAGREEMENT)
    passives = sum(len(re.findall(pat, lower_clean)) for pat in PASSIVE_VOICE)

    feats["article_error_density"] = float(art_errors / N)
    feats["sv_disagreement_density"] = float(sv_errors / N)
    feats["passive_voice_density"] = float(passives / N)

    # 5. Disfluency & repetitions
    repeats = sum(1 for i in range(1, N) if words[i] == words[i - 1])
    fillers = sum(1 for w in words if w in FILLERS)
    feats["repetition_count"] = float(repeats)
    feats["repetition_density"] = float(repeats / N)
    feats["disfluency_filler_count"] = float(fillers)
    feats["disfluency_filler_density"] = float(fillers / N)

    return feats


def extract_cola_acceptability(texts: List[str], batch_size: int = 32) -> List[Dict[str, float]]:
    """
    Directly scores grammatical acceptability of sentences using pretrained RoBERTa-CoLA.
    Outputs mean acceptability, min acceptability, unacceptable sentence ratio, severe error ratio,
    and length-weighted grammatical score.
    """
    model_name = "textattack/roberta-base-CoLA"
    device = "cuda:0" if torch.cuda.is_available() else "cpu"
    logger.info(f"Extracting RoBERTa-CoLA grammatical acceptability features ({device})...")
    tokenizer = AutoTokenizer.from_pretrained(model_name)
    model = AutoModelForSequenceClassification.from_pretrained(model_name)
    model.to(device)
    model.eval()

    all_results = []
    for t in tqdm(texts, desc="RoBERTa-CoLA Grammatical Scoring"):
        cleaned = clean_whisper_loops(t)
        sentences = [s.strip() for s in re.split(r"[.!?]+", cleaned) if len(s.strip()) > 3]
        if not sentences:
            all_results.append({
                "cola_prob_mean": 0.0,
                "cola_prob_min": 0.0,
                "cola_unacceptable_ratio": 1.0,
                "cola_severe_error_ratio": 1.0,
                "cola_perfect_ratio": 0.0,
                "cola_prob_std": 0.0,
                "cola_weighted_score": 0.0,
            })
            continue

        probs_acc = []
        word_lens = []
        with torch.no_grad():
            for i in range(0, len(sentences), batch_size):
                b_sents = sentences[i : i + batch_size]
                inputs = tokenizer(
                    b_sents,
                    padding=True,
                    truncation=True,
                    max_length=128,
                    return_tensors="pt",
                ).to(device)
                logits = model(**inputs).logits
                p = torch.softmax(logits, dim=-1)[:, 1].cpu().numpy()
                probs_acc.extend(p.tolist())
                word_lens.extend([len(s.split()) for s in b_sents])

        p_arr = np.array(probs_acc)
        w_arr = np.array(word_lens)
        total_w = max(1, np.sum(w_arr))

        all_results.append({
            "cola_prob_mean": float(np.mean(p_arr)),
            "cola_prob_min": float(np.min(p_arr)),
            "cola_unacceptable_ratio": float(np.mean(p_arr < 0.5)),
            "cola_severe_error_ratio": float(np.mean(p_arr < 0.2)),
            "cola_perfect_ratio": float(np.mean(p_arr > 0.9)),
            "cola_prob_std": float(np.std(p_arr)) if len(p_arr) > 1 else 0.0,
            "cola_weighted_score": float(np.sum(p_arr * w_arr) / total_w),
        })

    return all_results


def extract_dense_embeddings(
    texts: List[str], model_name: str, batch_size: int = 16
) -> np.ndarray:
    device = "cuda:0" if torch.cuda.is_available() else "cpu"
    logger.info(f"Extracting dense contextual embeddings with {model_name} on {device}...")
    tokenizer = AutoTokenizer.from_pretrained(model_name)
    model = AutoModel.from_pretrained(model_name)
    model.to(device)
    model.eval()

    all_embeds = []
    with torch.no_grad():
        for i in range(0, len(texts), batch_size):
            batch_texts = [clean_whisper_loops(t) or "Empty audio transcript." for t in texts[i : i + batch_size]]
            inputs = tokenizer(
                batch_texts,
                padding=True,
                truncation=True,
                max_length=512,
                return_tensors="pt",
            ).to(device)
            outputs = model(**inputs)
            mask = inputs["attention_mask"].unsqueeze(-1).expand(outputs.last_hidden_state.size()).float()
            sum_embeddings = torch.sum(outputs.last_hidden_state * mask, 1)
            sum_mask = torch.clamp(mask.sum(1), min=1e-9)
            mean_pooled = (sum_embeddings / sum_mask).cpu().numpy()
            all_embeds.append(mean_pooled)

    return np.vstack(all_embeds)


def build_feature_dataset(
    audio_dir: Path,
    csv_path: Path,
    transcripts_json: Path,
    is_train: bool = True,
) -> Tuple[pd.DataFrame, List[str]]:
    with open(transcripts_json, "r") as f:
        transcripts = json.load(f)

    df_meta = pd.read_csv(csv_path)
    records = []

    logger.info(f"Extracting multimodal features for {len(df_meta)} samples ({csv_path.stem})...")
    texts = []
    for _, row in tqdm(df_meta.iterrows(), total=len(df_meta), desc=f"Features {csv_path.stem}"):
        fn = row["filename"]
        audio_path = str(audio_dir / fn)
        tr = transcripts.get(fn, {})
        raw_txt = tr.get("text", "")
        cleaned_txt = clean_whisper_loops(raw_txt)
        texts.append(cleaned_txt)

        rec = {"filename": fn}
        if is_train and "label" in row:
            rec["label"] = float(row["label"])

        # 1. Acoustic & prosodic features
        ac_feats = extract_acoustic_features(audio_path)
        rec.update(ac_feats)

        # 2. Whisper temporal & fluency metrics with robust speaking rate
        ling_feats = extract_linguistic_features(raw_txt)
        rec.update(ling_feats)

        audio_dur = max(10.0, ac_feats["audio_duration"])
        raw_speech_dur = float(tr.get("speech_duration", 0.0))
        # Protect against silence-glitched speech duration
        effective_dur = raw_speech_dur if raw_speech_dur >= 10.0 else audio_dur
        rec["whisper_speech_duration"] = effective_dur
        rec["whisper_speaking_rate"] = float(rec["text_word_count"] / effective_dur)
        rec["whisper_articulation_rate"] = float(rec["text_word_count"] / max(5.0, effective_dur - float(tr.get("num_pauses", 0)) * float(tr.get("mean_pause", 0))))
        rec["whisper_num_pauses"] = float(tr.get("num_pauses", 0.0))
        rec["whisper_num_long_pauses"] = float(tr.get("num_long_pauses", 0.0))
        rec["whisper_mean_pause"] = float(tr.get("mean_pause", 0.0))
        rec["whisper_max_pause"] = float(tr.get("max_pause", 0.0))
        rec["whisper_silence_ratio"] = float(tr.get("silence_ratio", 0.0))

        records.append(rec)

    df_feats = pd.DataFrame(records)
    return df_feats, texts


def main():
    logger.info("Starting upgraded multimodal feature extraction...")

    df_train, texts_train = build_feature_dataset(
        TRAIN_DIR, TRAIN_CSV, TRANSCRIPTS_TRAIN_FILE, is_train=True
    )
    df_test, texts_test = build_feature_dataset(
        TEST_DIR, TEST_CSV, TRANSCRIPTS_TEST_FILE, is_train=False
    )

    # 3. Direct Grammatical Acceptability Modeling via RoBERTa-CoLA
    cola_train = extract_cola_acceptability(texts_train)
    cola_test = extract_cola_acceptability(texts_test)

    df_cola_tr = pd.DataFrame(cola_train)
    df_cola_te = pd.DataFrame(cola_test)
    for col in df_cola_tr.columns:
        df_train[col] = df_cola_tr[col]
        df_test[col] = df_cola_te[col]

    # 4. Dense Sentence-Transformer MiniLM-L6-v2 Embeddings (Top 24 components)
    logger.info("Extracting sentence grammar embeddings with all-MiniLM-L6-v2...")
    minilm_train = extract_dense_embeddings(texts_train, "sentence-transformers/all-MiniLM-L6-v2")
    minilm_test = extract_dense_embeddings(texts_test, "sentence-transformers/all-MiniLM-L6-v2")

    n_comp_minilm = min(24, minilm_train.shape[1], len(df_train))
    svd_minilm = TruncatedSVD(n_components=n_comp_minilm, random_state=42)
    minilm_svd_train = svd_minilm.fit_transform(minilm_train)
    minilm_svd_test = svd_minilm.transform(minilm_test)

    for c in range(n_comp_minilm):
        df_train[f"minilm_svd_{c}"] = minilm_svd_train[:, c]
        df_test[f"minilm_svd_{c}"] = minilm_svd_test[:, c]

    # 5. Dense DistilBERT Embeddings (Top 24 components)
    logger.info("Extracting contextual embeddings with distilbert-base-uncased...")
    bert_train = extract_dense_embeddings(texts_train, "distilbert-base-uncased")
    bert_test = extract_dense_embeddings(texts_test, "distilbert-base-uncased")

    n_comp_bert = min(24, bert_train.shape[1], len(df_train))
    svd_bert = TruncatedSVD(n_components=n_comp_bert, random_state=42)
    bert_svd_train = svd_bert.fit_transform(bert_train)
    bert_svd_test = svd_bert.transform(bert_test)

    for c in range(n_comp_bert):
        df_train[f"bert_svd_{c}"] = bert_svd_train[:, c]
        df_test[f"bert_svd_{c}"] = bert_svd_test[:, c]

    # 6. Syntactic N-Gram Collocations via TF-IDF (Top 16 components)
    logger.info("Extracting syntactic n-gram collocations via TF-IDF...")
    vec_word = TfidfVectorizer(ngram_range=(1, 2), min_df=3, max_features=3000)
    vec_char = TfidfVectorizer(analyzer="char_wb", ngram_range=(3, 5), min_df=5, max_features=5000)

    from scipy.sparse import hstack
    X_w_tr = vec_word.fit_transform(texts_train)
    X_c_tr = vec_char.fit_transform(texts_train)
    X_ngram_tr = hstack([X_w_tr, X_c_tr])

    X_w_te = vec_word.transform(texts_test)
    X_c_te = vec_char.transform(texts_test)
    X_ngram_te = hstack([X_w_te, X_c_te])

    n_comp_ngram = min(16, X_ngram_tr.shape[1], len(df_train))
    svd_ngram = TruncatedSVD(n_components=n_comp_ngram, random_state=42)
    ngram_svd_train = svd_ngram.fit_transform(X_ngram_tr)
    ngram_svd_test = svd_ngram.transform(X_ngram_te)

    for c in range(n_comp_ngram):
        df_train[f"ngram_svd_{c}"] = ngram_svd_train[:, c]
        df_test[f"ngram_svd_{c}"] = ngram_svd_test[:, c]

    # Save to Parquet
    FEATURES_TRAIN_FILE.parent.mkdir(parents=True, exist_ok=True)
    df_train.to_parquet(FEATURES_TRAIN_FILE, index=False)
    df_test.to_parquet(FEATURES_TEST_FILE, index=False)

    logger.info(f"Saved upgraded training features: {df_train.shape} -> {FEATURES_TRAIN_FILE}")
    logger.info(f"Saved upgraded test features:     {df_test.shape} -> {FEATURES_TEST_FILE}")
    logger.info("Upgraded feature extraction completed successfully!")


if __name__ == "__main__":
    main()
